#!/usr/bin/env python3
"""The ed25519 key pair that signs OTA images (nornInternal/nornCore/ota_plan.md step 3):
the private key as a PEM file (keep it; it is ignored by git) and the public key as a C
header the selector compiles in (boot/ota_pubkey.h).

    tools/ota_keygen.py [KEY.pem] [PUBKEY.h]        defaults ota_key.pem, boot/ota_pubkey.h

Does nothing if the key file exists (the header is regenerated from it). The build runs it
when the key is missing, so a fresh checkout gets a key of its own: its selector accepts
only images signed with that key, which is the point. For a product the key is made once,
kept off the build machines, and the header shipped."""
import sys, os
from cryptography.hazmat.primitives.asymmetric import ed25519
from cryptography.hazmat.primitives import serialization

def main():
    key_path = sys.argv[1] if len(sys.argv) > 1 else "ota_key.pem"
    hdr_path = sys.argv[2] if len(sys.argv) > 2 else "boot/ota_pubkey.h"
    if os.path.exists(key_path):
        key = serialization.load_pem_private_key(open(key_path, "rb").read(), None)
        made = False
    else:
        key = ed25519.Ed25519PrivateKey.generate()
        with open(key_path, "wb") as f:
            f.write(key.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8, serialization.NoEncryption()))
        os.chmod(key_path, 0o600)
        made = True
    pub = key.public_key().public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)
    with open(hdr_path, "w") as f:
        f.write("/* Generated by tools/ota_keygen.py from %s: the ed25519 public key the selector\n   verifies OTA images with. Not tracked by git. */\n" % key_path)
        f.write("static const unsigned char OTA_PUBKEY[32] = {\n    %s\n};\n" % ", ".join("0x%02x" % b for b in pub))
    print("ota key: %s %s, public key %s... in %s" % ("made" if made else "kept", key_path, pub.hex()[:16], hdr_path))

if __name__ == "__main__":
    main()
